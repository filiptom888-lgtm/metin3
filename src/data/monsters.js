/** Overworld / valley spawn rings (distance from map origin). Orc Isles use island tiers. */
/** Rings match current MAP_SIZE (252 → half 126). Orc Isles stay on their island scale. */
export const SPAWN_ZONES = {
  overworld: {
    near: { minR: 24, maxR: 48 },
    mid: { minR: 48, maxR: 88 },
    edge: { minR: 88, maxR: 120 },
  },
  valley: {
    near: { minR: 24, maxR: 48 },
    mid: { minR: 48, maxR: 88 },
    edge: { minR: 88, maxR: 120 },
  },
  orc_valley: {
    near: { minR: 12, maxR: 28 },
    mid: { minR: 28, maxR: 48 },
    edge: { minR: 48, maxR: 72 },
  },
  fire_plains: {
    near: { minR: 10, maxR: 32 },
    mid: { minR: 32, maxR: 55 },
    edge: { minR: 55, maxR: 82 },
  },
  desert: {
    near: { minR: 10, maxR: 32 },
    mid: { minR: 32, maxR: 55 },
    edge: { minR: 55, maxR: 82 },
  },
  snow: {
    near: { minR: 10, maxR: 32 },
    mid: { minR: 32, maxR: 55 },
    edge: { minR: 55, maxR: 82 },
  },
};

export function zoneAtDistance(mapId, dist) {
  const rings = SPAWN_ZONES[mapId] || SPAWN_ZONES.overworld;
  if (dist < rings.mid.minR) return "near";
  if (dist < rings.edge.minR) return "mid";
  return "edge";
}
